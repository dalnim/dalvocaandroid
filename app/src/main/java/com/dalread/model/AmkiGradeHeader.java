package com.dalread.model;

public class AmkiGradeHeader {

    private int primaryIconBackground;
    private String primaryIconText;
    private int secondaryIcon;
    private int thirdIcon;
    private int fourthIcon;
    private int itemCount;
    private String headerText;

    public int getPrimaryIconBackground() {
        return primaryIconBackground;
    }

    public void setPrimaryIconBackground(int primaryIconBackground) {
        this.primaryIconBackground = primaryIconBackground;
    }

    public String getPrimaryIconText() {
        return primaryIconText;
    }

    public void setPrimaryIconText(String primaryIconText) {
        this.primaryIconText = primaryIconText;
    }

    public int getSecondaryIcon() {
        return secondaryIcon;
    }

    public void setSecondaryIcon(int secondaryIcon) {
        this.secondaryIcon = secondaryIcon;
    }

    public int getThirdIcon() {
        return thirdIcon;
    }

    public void setThirdIcon(int thirdIcon) {
        this.thirdIcon = thirdIcon;
    }

    public int getFourthIcon() {
        return fourthIcon;
    }

    public void setFourthIcon(int fourthIcon) {
        this.fourthIcon = fourthIcon;
    }

    public int getItemCount() {
        return itemCount;
    }

    public void setItemCount(int itemCount) {
        this.itemCount = itemCount;
    }

    public String getHeaderText() {
        return headerText;
    }

    public void setHeaderText(String headerText) {
        this.headerText = headerText;
    }
}
